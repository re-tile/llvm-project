# RUN: llvm-mc -triple=tilegx --show-encoding %s | FileCheck %s

# Register names, immediates and a few representative pipes parse and encode.

# CHECK: add r0, r0, r1                          # encoding: [0x00,0x30,0x48,0x51,0x00,0x08,0x06,0x28]
add r0, r0, r1

# CHECK: addi sp, sp, -16                        # encoding: [0x00,0x30,0x48,0x51,0xdb,0x86,0x0f,0x18]
addi sp, sp, -16

# CHECK: moveli r0, 1234                         # encoding: [0x00,0x30,0x48,0x51,0xe0,0x97,0x26,0x00]
moveli r0, 1234

# CHECK: shl16insli r0, r0, 5                    # encoding: [0x00,0x30,0x48,0x51,0x00,0x28,0x00,0x38]
shl16insli r0, r0, 5

# CHECK: ld r0, r1                               # encoding: [0x00,0x30,0x1c,0x34,0x00,0x40,0x06,0x9e]
ld r0, r1

# CHECK: st sp, lr                               # encoding: [0x00,0x30,0x6c,0x37,0x00,0x40,0xbe,0xdf]
st sp, lr

# CHECK: jr lr                                   # encoding: [0x00,0x30,0x48,0x51,0xe0,0x76,0x6a,0x28]
jr lr
