// This file defines an instruction selector for the Tile target.
//
// First-light subset: relies on the tablegen-generated matcher plus the
// frameindex complex pattern. Custom selection of float, 64-bit multiply,
// network intrinsics and the PIC header is staged in over later phases.
//
